"""Generates the Stellaris bridge: votc_stellaris/events/votc_events.txt (the logging) and
votc_stellaris/common/scripted_effects/votc_scripted_effects.txt (entry points).

    python paradox_mods/build_stellaris_effects.py

The log lines live in events, not scripted effects: Stellaris runs scripted effects through its
macro preprocessor, which reads "[This.GetName]" as a macro ("Invalid macro entry") and the
names came out empty. Event files are not preprocessed.

Stellaris event targets cannot have computed names, so every listed empire gets one of
MAX_EMPIRES fixed slots (votc_e1 .. votc_eN); the player is votc_e0. The app addresses
empires as E0..EN (see src/main/games/paradox/commands.ts).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'votc_stellaris', 'common', 'scripted_effects', 'votc_scripted_effects.txt')
EVENTS = os.path.join(HERE, 'votc_stellaris', 'events', 'votc_events.txt')
MAX_EMPIRES = 30

EFFECTS = """# GENERATED by paradox_mods/build_stellaris_effects.py - edit that script instead.
# VOTC Bridge for Stellaris (GPL-3.0, see LICENSE.txt). Entry points only: the log lines are
# in events/votc_events.txt (the macro preprocessor of scripted effects mangles names).
# Runs in the scope of the player's country.

# refresh command of the app
votc_snapshot_refresh = {
	country_event = { id = votc.1 }
}

# The "Open communications (VOTC)" decision of the capital: the snapshot, the player's own
# leaders and a request to open the app's list of conversation partners.
votc_talk_from_decision = {
	country_event = { id = votc.2 }
}
"""

# THIS = a leader of the player's empire (E0)
LEADER = """
			if = {
				limit = { is_ruler = yes }
				log = "VOTC|CH|E0|[This.GetName]|ruler|yes"
				log = "VOTC|CH|E0|[This.GetName]|title|Ruler"
			}
			else_if = {
				limit = { leader_class = commander }
				log = "VOTC|CH|E0|[This.GetName]|title|Commander"
			}
			else_if = {
				limit = { leader_class = official }
				log = "VOTC|CH|E0|[This.GetName]|title|Official"
			}
			else_if = {
				limit = { leader_class = scientist }
				log = "VOTC|CH|E0|[This.GetName]|title|Scientist"
			}
			if = {
				limit = { gender = female }
				log = "VOTC|CH|E0|[This.GetName]|gender|female"
			}
			else = {
				log = "VOTC|CH|E0|[This.GetName]|gender|male"
			}
			log = "VOTC|CH|E0|[This.GetName]|species|[This.GetSpeciesName]"
"""

# BEGIN, campaign data, the player and the empires it has contact with (THIS = the player)
HEAD = """
		save_global_event_target_as = votc_e0
		set_variable = { which = votc_i value = 0 }
		log = "VOTC|BEGIN|stellaris|2|snapshot"
		log = "VOTC|META|campaign|0"
		log = "VOTC|META|date|[GetDate]"
		log = "VOTC|P|tag|E0"
		log = "VOTC|P|name|[This.GetName]"
		log = "VOTC|P|leader|[This.GetRulerName]"
		log = "VOTC|P|leader_title|[This.GetRulerTitle]"
		log = "VOTC|P|government|[This.GetGovernmentName]"
		log = "VOTC|P|species|[This.GetSpeciesName]"
		every_playable_country = {
			limit = { is_at_war_with = prev }
			log = "VOTC|P|war_with|[This.GetName]"
		}
		every_playable_country = {
			limit = {
				NOT = { is_same_value = prev }
				has_communications = prev
			}
			prev = { change_variable = { which = votc_i value = 1 } }
			# THIS = an empire, PREV = the player's country (its votc_i is this empire's slot)
"""

SLOT = '''	if = {{
		limit = {{ prev = {{ check_variable = {{ which = votc_i value = {n} }} }} }}
		save_global_event_target_as = votc_e{n}
		log = "VOTC|C|E{n}|name|[This.GetName]"
		log = "VOTC|C|E{n}|leader|[This.GetRulerName]"
		log = "VOTC|C|E{n}|leader_title|[This.GetRulerTitle]"
		log = "VOTC|C|E{n}|government|[This.GetGovernmentName]"
		log = "VOTC|C|E{n}|species|[This.GetSpeciesName]"
		every_playable_country = {{ limit = {{ is_at_war_with = prev }} log = "VOTC|C|E{n}|war_with|[This.GetName]" }}
		if = {{ limit = {{ is_at_war_with = prev }} log = "VOTC|R|E{n}|war|yes" }}
		if = {{ limit = {{ is_in_federation_with = prev }} log = "VOTC|R|E{n}|ally|yes" }}
		if = {{ limit = {{ has_defensive_pact = prev }} log = "VOTC|R|E{n}|defensive_pact|yes" }}
		if = {{ limit = {{ has_non_aggression_pact = prev }} log = "VOTC|R|E{n}|non_aggression_pact|yes" }}
		if = {{ limit = {{ is_subject = yes overlord = {{ is_same_value = prev }} }} log = "VOTC|R|E{n}|subject|yes" }}
		if = {{ limit = {{ prev = {{ is_subject = yes overlord = {{ is_same_value = prevprev }} }} }} log = "VOTC|R|E{n}|overlord|yes" }}
		if = {{ limit = {{ opinion = {{ who = prev value > 99 }} }} log = "VOTC|R|E{n}|opinion|75" }}
		else_if = {{ limit = {{ opinion = {{ who = prev value > 24 }} }} log = "VOTC|R|E{n}|opinion|40" }}
		else_if = {{ limit = {{ opinion = {{ who = prev value > -25 }} }} log = "VOTC|R|E{n}|opinion|0" }}
		else_if = {{ limit = {{ opinion = {{ who = prev value > -100 }} }} log = "VOTC|R|E{n}|opinion|-40" }}
		else = {{ log = "VOTC|R|E{n}|opinion|-75" }}
	}}
'''


def event(id_, comment, body):
    return (f'# {comment}\ncountry_event = {{\n\tid = {id_}\n\thide_window = yes\n\tis_triggered_only = yes\n'
            f'\ttrigger = {{\n\t\tis_ai = no\n\t}}\n\timmediate = {{{body}\t}}\n}}\n')


def main():
    slots = ''.join('\t\t' + SLOT.format(n=n).replace('\n\t', '\n\t\t\t') for n in range(1, MAX_EMPIRES + 1))
    head = HEAD + slots.rstrip('\t') + '\t\t}\n'
    events = [
        '# GENERATED by paradox_mods/build_stellaris_effects.py - edit that script instead.\n'
        '# VOTC Bridge for Stellaris (GPL-3.0, see LICENSE.txt). Line format: see\n'
        '# src/main/games/paradox/types.ts in the VOTC source.\n'
        'namespace = votc\n\n',
        event('votc.1', 'Snapshot for the VOTC app (monthly, game start, refresh command)', head + '\t\tlog = "VOTC|END"\n'),
        '\n',
        event('votc.2', 'The "Open communications (VOTC)" decision: the snapshot, the player\'s leaders, open the app\'s list',
              head + '\t\tlog = "VOTC|META|talk|pick"\n\t\tevery_owned_leader = {' + LEADER + '\t\t}\n\t\tlog = "VOTC|END"\n'),
    ]
    for path, text in ((OUT, EFFECTS), (EVENTS, ''.join(events))):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8-sig', newline='\n') as f:
            f.write(text)
        print('wrote', path)


main()
