"""Generates the trait-logging effects of the Victoria 3 and EU5 bridges from the games' own
trait files (no localisation function prints a character's traits, so each one is a check).

usage: python paradox_mods/build_trait_logs.py [<steamapps/common folder>]
Re-run after a game update that adds traits; the output files are committed.
"""
import glob, os, re, sys

COMMON = sys.argv[1] if len(sys.argv) > 1 else r'C:\Program Files (x86)\Steam\steamapps\common'
HERE = os.path.dirname(os.path.abspath(__file__))

GAMES = {
    'vic3': {
        'traits': os.path.join(COMMON, 'Victoria 3', 'game', 'common', 'character_traits'),
        'out': os.path.join(HERE, 'votc_vic3', 'common', 'scripted_effects', 'votc_trait_effects.txt'),
        'prefix': 'VOTC|CH|[THIS.GetCharacter.GetCountry.GetTagName]|[THIS.GetCharacter.GetFullNameNoFormatting]|trait|',
        'log': 'debug_log',
    },
    'eu5': {
        'traits': os.path.join(COMMON, 'Europa Universalis V', 'game', 'in_game', 'common', 'traits'),
        'out': os.path.join(HERE, 'votc_eu5', 'in_game', 'common', 'scripted_effects', 'votc_trait_effects.txt'),
        'prefix': "VOTC|CH|[SCOPE.sCountry('votc_talker_country').GetTag]|[SCOPE.sCharacter('votc_talker').GetName]|trait|",
        'log': 'debug_log',
    },
}


def trait_keys(folder):
    keys = []
    for f in sorted(glob.glob(os.path.join(folder, '*.txt'))):
        for line in open(f, encoding='utf-8-sig'):
            m = re.match(r'^([a-z_0-9]+)\s*=\s*\{', line)
            if m and m.group(1) not in keys:
                keys.append(m.group(1))
    return keys


def main():
    for game, g in GAMES.items():
        keys = trait_keys(g['traits'])
        if not keys:
            sys.exit(f'{game}: no traits found in {g["traits"]}')
        lines = [
            f'# Generated by paradox_mods/build_trait_logs.py from the game\'s {len(keys)} traits; do not edit.',
            '# THIS = a character',
            'votc_log_character_traits = {',
        ]
        for k in keys:
            lines.append(f'\tif = {{ limit = {{ has_trait = {k} }} {g["log"]} = "{g["prefix"]}{k}" }}')
        lines.append('}')
        os.makedirs(os.path.dirname(g['out']), exist_ok=True)
        with open(g['out'], 'w', encoding='utf-8-sig', newline='\n') as f:
            f.write('\n'.join(lines) + '\n')
        print(f'{game}: {len(keys)} traits -> {g["out"]}')


main()
